    function setPresetDate(preset) {
        const sd = document.getElementById('start_date');
        const ed = document.getElementById('end_date');
        const now = new Date();
        
        if (preset === 'today') {
            const todayStr = now.toISOString().split('T')[0];
            sd.value = todayStr;
            ed.value = todayStr;
        } else if (preset === 'month') {
            const firstDay = new Date(now.getFullYear(), now.getMonth(), 1).toISOString().split('T')[0];
            const todayStr = now.toISOString().split('T')[0];
            sd.value = firstDay;
            ed.value = todayStr;
        } else if (preset === 'year') {
            sd.value = '2025-01-01';
            ed.value = '2025-12-31';
        }
        
        document.getElementById('history-filter-form').submit();
    }

    // Sync export links on date change
    (function() {

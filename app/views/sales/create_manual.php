// ── Form submit (AJAX) ──────────────────────────────────────────────
document.addEventListener('DOMContentLoaded', () => {
    hposRenderGrid();

    document.getElementById('manual-sale-form').addEventListener('submit', function(e) {
        e.preventDefault();

        if (!hSelectedPM) {
            showToast('Debes seleccionar un método de pago (Efectivo o QR).', 'warning');
            return;
        }

        const cartIds = Object.keys(hcart).filter(id => hcart[id] > 0);
        if (!cartIds.length) {
            showToast('Añade al menos un producto al pedido antes de guardar.', 'warning');
            return;
        }

        const submitBtn = document.getElementById('submit-btn');
        submitBtn.disabled = true;
        submitBtn.innerHTML = `⏳ Guardando...`;

        const formData = new FormData(this);

        fetch(this.action, {
            method: 'POST',
            body: formData,
            headers: { 'X-Requested-With': 'XMLHttpRequest' }
        })
        .then(res => res.json())
        .then(data => {
            submitBtn.disabled = false;
            submitBtn.innerHTML = `✅ Guardar Pedido`;

            if (data.success) {
                showToast(data.message || '¡Pedido histórico guardado exitosamente!', 'success');
                hposClearCart();
                hSelectedPM = null;
                document.getElementById('payment_method').value = '';
                // Reset PM button styles
                const inact = 'pm-btn flex items-center justify-center gap-1.5 py-3 px-3 rounded-xl font-extrabold text-sm border-2 border-cream-dark bg-white hover:bg-cream-dark text-coffee-dark transition-all';
                const pmEf = document.getElementById('pm-btn-efectivo');
                const pmQr = document.getElementById('pm-btn-qr');
                const pmEfMob = document.getElementById('pm-btn-efectivo-mob');
                const pmQrMob = document.getElementById('pm-btn-qr-mob');
                if (pmEf) pmEf.className = inact;
                if (pmQr) pmQr.className = inact;
                if (pmEfMob) pmEfMob.className = 'pm-btn-mob flex items-center justify-center gap-1.5 py-3 rounded-xl font-extrabold text-sm border-2 border-cream-dark bg-white text-coffee-dark transition-all';
                if (pmQrMob) pmQrMob.className = 'pm-btn-mob flex items-center justify-center gap-1.5 py-3 rounded-xl font-extrabold text-sm border-2 border-cream-dark bg-white text-coffee-dark transition-all';
            } else {
                showToast(data.message || 'Error al guardar el pedido.', 'error');
            }
        })
        .catch(() => {
            submitBtn.disabled = false;
            submitBtn.innerHTML = `✅ Guardar Pedido`;
            showToast('Error de conexión al servidor. Intenta de nuevo.', 'error');
        });
    });
});

    function generateComboboxOptionsHtml(rowIndex, query = '') {
        query = query.toLowerCase().trim();
        const filtered = availableProducts.filter(p => {
            if (!query) return true;
            return p.name.toLowerCase().includes(query) || (p.code || '').toLowerCase().includes(query) || (p.category_name || '').toLowerCase().includes(query);
        });

        if (!filtered.length) {
            return `<div class="p-3 text-center text-xs text-coffee-light font-semibold">Sin coincidencias</div>`;
        }

        return filtered.map(p => {
            const iconBadge = getColoredIconBadge(p.category_icon, 'w-7 h-7', 'w-3.5 h-3.5');
            return `
                <div onclick="selectComboboxOption(${rowIndex}, ${p.id})"
                     class="flex items-center justify-between p-2 rounded-xl hover:bg-cream/60 cursor-pointer transition group">
                    <div class="flex items-center gap-2.5 min-w-0">
                        ${iconBadge}
                        <div class="truncate">
                            <p class="text-xs font-bold text-coffee-dark leading-snug group-hover:text-accent transition-colors truncate">${p.name}</p>
                            <span class="text-[10px] text-coffee-light/70 truncate">${p.category_name}</span>
                        </div>
                    </div>
                    <span class="text-xs font-extrabold text-accent shrink-0 ml-2 font-heading">Bs. ${parseFloat(p.price).toFixed(2)}</span>
                </div>
            `;
        }).join('');
    }

    function toggleCombobox(rowIndex) {
        const menu = document.getElementById(`combobox-menu-${rowIndex}`);
        if (!menu) return;

        const isHidden = menu.classList.contains('hidden');

        // Close any other open combobox
        document.querySelectorAll('.combobox-menu').forEach(m => m.classList.add('hidden'));

        if (isHidden) {
            menu.classList.remove('hidden');
            openComboboxIndex = rowIndex;
            // Focus search input
            const input = menu.querySelector('input');
            if (input) {
                input.value = '';
                filterComboboxOptions(rowIndex, '');
                setTimeout(() => input.focus(), 50);
            }
        } else {
            menu.classList.add('hidden');
            openComboboxIndex = null;
        }
    }

    function filterComboboxOptions(rowIndex, query) {
        const optsContainer = document.getElementById(`combobox-opts-${rowIndex}`);
        if (optsContainer) {
            optsContainer.innerHTML = generateComboboxOptionsHtml(rowIndex, query);
        }
    }

    function selectComboboxOption(rowIndex, productId) {
        setRowProduct(rowIndex, productId);
        const menu = document.getElementById(`combobox-menu-${rowIndex}`);
        if (menu) menu.classList.add('hidden');
        openComboboxIndex = null;
    }

    function setRowProduct(rowIndex, productId) {
        const product = availableProducts.find(p => p.id == productId);
        if (!product) return;

        const tr = document.getElementById(`row-${rowIndex}`);
        if (!tr) return;

        tr.setAttribute('data-product-id', productId);

        // Update trigger label
        const iconBadge = getColoredIconBadge(product.category_icon, 'w-7 h-7', 'w-3.5 h-3.5');
        const labelEl = document.getElementById(`combobox-label-${rowIndex}`);
        if (labelEl) {
            labelEl.innerHTML = `
                ${iconBadge}
                <span class="font-extrabold text-coffee-dark text-xs truncate">${product.name}</span>
                <span class="text-[10px] text-coffee-light bg-cream px-1.5 py-0.5 rounded-md border border-cream-dark shrink-0">${product.category_name}</span>
            `;
        }

        // Set hidden input name and price
        const realQtyInput = document.getElementById(`qty-real-${rowIndex}`);
        if (realQtyInput) {
            realQtyInput.name = `items[${product.id}]`;
        }

        const priceEl = document.getElementById(`price-${rowIndex}`);
        if (priceEl) {
            priceEl.innerText = `Bs. ${parseFloat(product.price).toFixed(2)}`;
        }

        // Set default quantity to 1 if zero
        const qtyInput = document.getElementById(`qty-${rowIndex}`);
        if (qtyInput) {
            if (parseInt(qtyInput.value) <= 0) {
                qtyInput.value = 1;
                if (realQtyInput) realQtyInput.value = 1;
            }
        }

        recalculateSubtotal(rowIndex);
    }

    function updateQty(rowIndex, delta) {
        const qtyInput = document.getElementById(`qty-${rowIndex}`);
        let qty = parseInt(qtyInput.value) || 0;
        qty = Math.max(0, qty + delta);
        qtyInput.value = qty;

        const realQtyInput = document.getElementById(`qty-real-${rowIndex}`);
        if (realQtyInput) realQtyInput.value = qty;

        recalculateSubtotal(rowIndex);
    }

    function onQtyChange(rowIndex, inputEl) {
        const qty = Math.max(0, parseInt(inputEl.value) || 0);
        inputEl.value = qty;

        const realQtyInput = document.getElementById(`qty-real-${rowIndex}`);
        if (realQtyInput) realQtyInput.value = qty;

        recalculateSubtotal(rowIndex);
    }

    function recalculateSubtotal(rowIndex) {
        const tr = document.getElementById(`row-${rowIndex}`);
        if (!tr) return;

        const productId = tr.getAttribute('data-product-id');
        const product = availableProducts.find(p => p.id == productId);
        const price = product ? parseFloat(product.price) : 0;

        const qty = parseInt(document.getElementById(`qty-${rowIndex}`).value) || 0;
        const subtotal = price * qty;

        const subtotalEl = document.getElementById(`subtotal-${rowIndex}`);
        if (subtotalEl) {
            subtotalEl.innerText = `Bs. ${subtotal.toFixed(2)}`;
        }

        calculateGrandTotal();
    }

    function removeRow(rowIndex) {
        const row = document.getElementById(`row-${rowIndex}`);
        if (row) {
            row.remove();
            calculateGrandTotal();
            checkTableEmptyState();
        }
    }

    function clearAllRows() {
        document.getElementById('items-container').innerHTML = '';
        calculateGrandTotal();
        checkTableEmptyState();
    }

    function checkTableEmptyState() {
        const container = document.getElementById('items-container');
        const emptyState = document.getElementById('table-empty-state');
        if (!container.children.length) {
            emptyState.classList.remove('hidden');
        } else {
            emptyState.classList.add('hidden');
        }
    }

    function calculateGrandTotal() {
        let total = 0;
        const rows = document.querySelectorAll('#items-container tr');
        rows.forEach(row => {
            const productId = row.getAttribute('data-product-id');
            const product = availableProducts.find(p => p.id == productId);
            const price = product ? parseFloat(product.price) : 0;
            const rIndex = row.id.split('-')[1];
            const qtyInput = document.getElementById(`qty-${rIndex}`);
            const qty = qtyInput ? (parseInt(qtyInput.value) || 0) : 0;
            total += price * qty;
        });

        document.getElementById('grand-total').innerText = `Bs. ${total.toFixed(2)}`;
    }


    // ─── Add or Increment Product ──────────────────────────────────────────────
    function addOrIncrementProduct(productId) {
        const product = availableProducts.find(p => p.id == productId);
        if (!product) return;

        // Check if row already exists for this product
        const existingRows = document.querySelectorAll('#items-container tr');
        let foundRow = null;

        existingRows.forEach(tr => {
            const selectedVal = tr.getAttribute('data-product-id');
            if (selectedVal == productId) {
                foundRow = tr;
            }
        });

        if (foundRow) {
            const rIndex = foundRow.id.split('-')[1];
            updateQty(rIndex, 1);
            // Flash effect
            foundRow.classList.add('bg-amber-100/50');
            setTimeout(() => foundRow.classList.remove('bg-amber-100/50'), 400);
        } else {
            // Find empty row or add new
            let emptyTr = null;
            existingRows.forEach(tr => {
                if (!tr.getAttribute('data-product-id')) {
                    emptyTr = tr;
                }
            });

            if (emptyTr) {
                const rIndex = emptyTr.id.split('-')[1];
                setRowProduct(rIndex, productId);
            } else {
                addRow(productId);
            }
        }
    }


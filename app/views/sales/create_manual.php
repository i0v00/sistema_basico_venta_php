// ── Cart ───────────────────────────────────────────────────────────
function hposAddToCart(productId) {
    hcart[productId] = (hcart[productId] || 0) + 1;
    hposRenderCart();
    hposRenderGrid();
}

function hposChangeQty(productId, delta) {
    hcart[productId] = Math.max(0, (hcart[productId] || 0) + delta);
    if (hcart[productId] === 0) delete hcart[productId];
    hposRenderCart();
    hposRenderGrid();
}

function hposRemoveItem(productId) {
    delete hcart[productId];
    hposRenderCart();
    hposRenderGrid();
}

function hposClearCart() {
    hcart = {};
    hposRenderCart();
    hposRenderGrid();
}

function hposRenderCart() {
    const itemsEl    = document.getElementById('hcart-items');
    const itemsMob   = document.getElementById('hcart-items-mob');
    const emptyEl    = document.getElementById('hcart-empty');
    const totalEl    = document.getElementById('hcart-total');
    const totalMob   = document.getElementById('hcart-total-mob');
    const fabBadge   = document.getElementById('mob-hfab-badge');

    const ids = Object.keys(hcart).filter(id => hcart[id] > 0);

    let total = 0;
    let html = '';

    ids.forEach(id => {
        const p = HPOS_PRODUCTS.find(x => x.id == id);
        if (!p) return;
        const qty = hcart[id];
        const subtotal = parseFloat(p.price) * qty;
        total += subtotal;

        const col = HCAT_COLORS[p.category_icon] || { bg:'#F5F5F4', text:'#57534E', border:'#E7E5E4' };
        let iconHtml;
        if (HPOS_ICONS[p.category_icon]) {
            const inner = HPOS_ICONS[p.category_icon].replace(/^<svg[^>]*>/,'').replace('</svg>','');
            iconHtml = `<div style="width:36px;height:36px;background:${col.bg};color:${col.text};border:2px solid ${col.border};border-radius:9px;display:flex;align-items:center;justify-content:center;flex-shrink:0;">
                <svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>
            </div>`;
        } else {
            iconHtml = `<div style="width:36px;height:36px;background:#F5F5F4;border-radius:9px;display:flex;align-items:center;justify-content:center;font-size:16px;flex-shrink:0;">${p.category_icon || '🏷️'}</div>`;
        }

        html += `
            <div class="cart-row-anim flex items-center gap-2.5 p-2.5 bg-cream/30 rounded-xl border border-cream-dark/60">
                ${iconHtml}
                <div class="flex-1 min-w-0">
                    <p class="text-xs font-extrabold text-coffee-dark leading-tight truncate">${p.name}</p>
                    <p class="text-[11px] text-coffee-light font-semibold">Bs. ${parseFloat(p.price).toFixed(2)} c/u</p>
                </div>
                <div class="flex items-center gap-1 shrink-0">
                    <button type="button" onclick="hposChangeQty(${id}, -1)"
                            class="w-7 h-7 rounded-lg bg-white border border-cream-dark text-coffee-dark font-black text-sm hover:bg-red-50 hover:text-red-600 transition flex items-center justify-center">−</button>
                    <span class="w-7 text-center font-black text-sm text-coffee-dark">${qty}</span>
                    <button type="button" onclick="hposChangeQty(${id}, 1)"
                            class="w-7 h-7 rounded-lg bg-white border border-cream-dark text-coffee-dark font-black text-sm hover:bg-emerald-50 hover:text-emerald-600 transition flex items-center justify-center">+</button>
                </div>
                <div class="text-right shrink-0">
                    <p class="text-xs font-black text-coffee-dark font-heading">Bs. ${subtotal.toFixed(2)}</p>
                    <button type="button" onclick="hposRemoveItem(${id})" class="text-[10px] text-rose-500 hover:text-rose-700 font-bold mt-0.5">Quitar</button>
                </div>
                <!-- Hidden input for form POST -->
                <input type="hidden" name="items[${id}]" value="${qty}">
            </div>`;
    });

    // Show / hide empty state
    if (emptyEl) emptyEl.style.display = ids.length ? 'none' : 'flex';
    if (itemsEl) {
        // Replace all rows (keep empty state el)
        const existingRows = itemsEl.querySelectorAll('.cart-row-anim');
        existingRows.forEach(r => r.remove());
        // Also remove old hidden inputs
        itemsEl.querySelectorAll('input[type=hidden]').forEach(i => i.remove());
        itemsEl.insertAdjacentHTML('beforeend', html);
    }
    if (itemsMob) itemsMob.innerHTML = html;

    const totalStr = `Bs. ${total.toFixed(2)}`;
    if (totalEl)  totalEl.innerText  = totalStr;
    if (totalMob) totalMob.innerText = totalStr;
    if (fabBadge) fabBadge.innerText = ids.length;
}

// ── Payment Method ──────────────────────────────────────────────────
function hposSelectPM(method) {
    hSelectedPM = method;
    document.getElementById('payment_method').value = method;

    const btnEf    = document.getElementById('pm-btn-efectivo');
    const btnQr    = document.getElementById('pm-btn-qr');
    const btnEfMob = document.getElementById('pm-btn-efectivo-mob');
    const btnQrMob = document.getElementById('pm-btn-qr-mob');

    const activeClass   = 'pm-btn flex items-center justify-center gap-1.5 py-3 px-3 rounded-xl font-extrabold text-sm border-2 shadow-md transition-all';
    const inactiveClass = 'pm-btn flex items-center justify-center gap-1.5 py-3 px-3 rounded-xl font-extrabold text-sm border-2 border-cream-dark bg-white hover:bg-cream-dark text-coffee-dark transition-all';
    const activeMobClass  = 'pm-btn-mob flex items-center justify-center gap-1.5 py-3 rounded-xl font-extrabold text-sm border-2 shadow-md transition-all';
    const inactiveMobClass = 'pm-btn-mob flex items-center justify-center gap-1.5 py-3 rounded-xl font-extrabold text-sm border-2 border-cream-dark bg-white text-coffee-dark transition-all';

    if (method === 'efectivo') {
        if (btnEf) { btnEf.className = activeClass + ' border-emerald-600 bg-emerald-600 text-white scale-[1.02]'; }
        if (btnQr) { btnQr.className = inactiveClass; }
        if (btnEfMob) { btnEfMob.className = activeMobClass + ' border-emerald-600 bg-emerald-600 text-white'; }
        if (btnQrMob) { btnQrMob.className = inactiveMobClass; }
    } else {
        if (btnQr) { btnQr.className = activeClass + ' border-blue-600 bg-blue-600 text-white scale-[1.02]'; }
        if (btnEf) { btnEf.className = inactiveClass; }
        if (btnQrMob) { btnQrMob.className = activeMobClass + ' border-blue-600 bg-blue-600 text-white'; }
        if (btnEfMob) { btnEfMob.className = inactiveMobClass; }
    }
}


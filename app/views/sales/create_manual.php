// ── Icon Badge ─────────────────────────────────────────────────────
function hposIconBadge(iconKey, size = 36) {
    const col = HCAT_COLORS[iconKey] || { bg:'#F5F5F4', text:'#57534E', border:'#E7E5E4' };
    const s = `width:${size}px;height:${size}px;background:${col.bg};color:${col.text};border:2px solid ${col.border};border-radius:10px;display:flex;align-items:center;justify-content:center;flex-shrink:0;`;
    if (HPOS_ICONS[iconKey]) {
        const iconSize = Math.round(size * 0.55);
        return `<div style="${s}"><svg xmlns="http://www.w3.org/2000/svg" width="${iconSize}" height="${iconSize}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${HPOS_ICONS[iconKey].replace(/^<svg[^>]*>/,'').replace('</svg>','')}</svg></div>`;
    }
    return `<div style="${s};font-size:${Math.round(size*.45)}px;">${iconKey || '🏷️'}</div>`;
}

// ── Render product grid ────────────────────────────────────────────
function hposRenderGrid() {
    const query = (document.getElementById('hpos-search')?.value || '').toLowerCase().trim();
    const grid  = document.getElementById('hpos-grid');
    const empty = document.getElementById('hpos-empty');

    const filtered = HPOS_PRODUCTS.filter(p => {
        if (hCurrentCat !== null && parseInt(p.category_id) !== hCurrentCat) return false;
        if (query && !p.name.toLowerCase().includes(query) && !(p.code || '').toLowerCase().includes(query)) return false;
        return true;
    });

    grid.innerHTML = '';
    if (!filtered.length) { empty.classList.remove('hidden'); empty.style.display='flex'; return; }
    empty.classList.add('hidden'); empty.style.display='none';

    filtered.forEach(p => {
        const inCart = hcart[p.id] > 0;
        const col = HCAT_COLORS[p.category_icon] || { bg:'#F5F5F4', text:'#57534E', border:'#E7E5E4' };
        const card = document.createElement('div');
        card.className = 'prod-card-anim relative bg-white rounded-2xl border-2 border-cream-dark overflow-hidden cursor-pointer transition-all duration-200 select-none';
        if (inCart) card.style.borderColor = '#E07B39';

        // Build icon html (inline SVG without outer wrapper tag)
        const iconSize = 40;
        let iconHtml;
        if (HPOS_ICONS[p.category_icon]) {
            const inner = HPOS_ICONS[p.category_icon].replace(/^<svg[^>]*>/,'').replace('</svg>','');
            iconHtml = `<div style="width:${iconSize}px;height:${iconSize}px;background:${col.bg};color:${col.text};border:2px solid ${col.border};border-radius:10px;display:flex;align-items:center;justify-content:center;flex-shrink:0;margin:0 auto 8px;">
                <svg xmlns="http://www.w3.org/2000/svg" width="${Math.round(iconSize*.55)}" height="${Math.round(iconSize*.55)}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>
            </div>`;
        } else {
            iconHtml = `<div style="width:${iconSize}px;height:${iconSize}px;background:#F5F5F4;border-radius:10px;display:flex;align-items:center;justify-content:center;font-size:20px;margin:0 auto 8px;">${p.category_icon || '🏷️'}</div>`;
        }

        card.innerHTML = `
            ${inCart ? `<div style="position:absolute;top:6px;right:6px;background:#E07B39;color:#fff;font-size:10px;font-weight:900;width:20px;height:20px;border-radius:999px;display:flex;align-items:center;justify-content:center;">${hcart[p.id]}</div>` : ''}
            <div style="padding:14px 10px 10px;text-align:center;">
                ${iconHtml}
                <p style="font-size:12px;font-weight:800;color:#2C1810;line-height:1.3;margin-bottom:4px;display:-webkit-box;-webkit-line-clamp:2;-webkit-box-orient:vertical;overflow:hidden;">${p.name}</p>
                <p style="font-size:13px;font-weight:900;color:#E07B39;font-family:var(--font-heading,sans-serif);">Bs. ${parseFloat(p.price).toFixed(2)}</p>
            </div>
        `;

        card.onclick = (e) => {
            // Ripple
            const rect = card.getBoundingClientRect();
            const rip = document.createElement('div');
            rip.className = 'ripple-fx';
            rip.style.left = (e.clientX - rect.left - 25) + 'px';
            rip.style.top  = (e.clientY - rect.top  - 25) + 'px';
            card.appendChild(rip);
            setTimeout(() => rip.remove(), 600);

            hposAddToCart(p.id);
        };

        grid.appendChild(card);
    });
}

